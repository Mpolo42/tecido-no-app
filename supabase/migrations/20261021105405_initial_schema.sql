-- Baseline for a clean local project. Existing clinical rows and column defaults
-- are preserved when this migration is applied to the existing project.
create table if not exists public.pacientes (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  nome text not null,
  nome_social text,
  sexo text not null,
  idade integer not null,
  tipo_diabetes text not null,
  comorbidades text[],
  grau_lesao text not null,
  tempo_lesao text not null,
  localizacao_quadrante text not null,
  foto_url text,
  termo_consentimento boolean default false,
  whatsapp text
);

alter table public.pacientes enable row level security;
revoke all on public.pacientes from anon, authenticated;
grant select, insert, update, delete on public.pacientes to service_role;
revoke all on sequence public.pacientes_id_seq from anon, authenticated;
grant usage, select on sequence public.pacientes_id_seq to service_role;

comment on table public.pacientes is
  'Patient records. Direct public intake is denied; access is explicitly granted by the security migration.';
